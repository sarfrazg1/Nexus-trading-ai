package com.example.data.signal

import com.example.data.model.CandleTimeframe
import com.example.data.model.Signal
import com.example.data.model.SignalStatus
import com.example.data.model.SignalType
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

/**
 * Three strict signal decisions permitted by NEXUS AI Trading Engine:
 * LONG, SHORT, or NO TRADE.
 */
enum class SignalDecision(val label: String, val description: String) {
    LONG("LONG", "High-probability bullish expansion opportunity"),
    SHORT("SHORT", "High-probability bearish contraction/reversal opportunity"),
    NO_TRADE("NO TRADE", "No high-probability trade opportunity / Conflicting conditions")
}

/**
 * Individual factor breakdown for transparent confidence scoring.
 */
data class SignalFactorReason(
    val factorName: String,
    val maxPoints: Int,
    val awardedPoints: Int,
    val stance: String, // "BULLISH", "BEARISH", "NEUTRAL", "CONFLICTING"
    val summary: String
)

/**
 * Transparent weighted confidence scoring system.
 * Weights:
 * - Trend direction: 20%
 * - Momentum: 15%
 * - Volume: 15%
 * - Market Structure (SMC): 20%
 * - Liquidity: 10%
 * - Support & Resistance: 10%
 * - Multi-Timeframe Confirmation: 10%
 */
data class ConfidenceScoreBreakdown(
    val trendScore: Int,             // out of 20
    val momentumScore: Int,          // out of 15
    val volumeScore: Int,            // out of 15
    val marketStructureScore: Int,   // out of 20
    val liquidityScore: Int,         // out of 10
    val supportResistanceScore: Int, // out of 10
    val multiTimeframeScore: Int,    // out of 10
    val totalScore: Int,             // 0 .. 100
    val rating: String,              // "High Confluence", "Moderate Confluence", "Unclear / Chop"
    val factors: List<SignalFactorReason>
)

/**
 * Disciplined risk management plan.
 * Strict stop loss calculation using market structure and ATR buffers.
 * Take profit levels derived from risk/reward and liquidity/Fibonacci zones.
 * Suggested leverage strictly capped based on volatility.
 */
data class RiskManagementPlan(
    val entryPrice: Double,
    val entryZoneMin: Double,
    val entryZoneMax: Double,
    val entryZoneFormatted: String,
    val stopLoss: Double,
    val stopLossFormatted: String,
    val stopLossDistancePercent: Double,
    val takeProfit1: Double,
    val takeProfit1Formatted: String,
    val takeProfit1DistancePercent: Double,
    val takeProfit2: Double,
    val takeProfit2Formatted: String,
    val takeProfit2DistancePercent: Double,
    val takeProfit3: Double,
    val takeProfit3Formatted: String,
    val takeProfit3DistancePercent: Double,
    val riskRewardRatio: Double,
    val riskRewardFormatted: String,
    val estimatedRiskPercent: Double,
    val potentialRewardPercent: Double,
    val suggestedMaxLeverage: Int, // Capped at 2x - 10x max based on ATR %
    val leverageTier: String,       // e.g. "Low Risk (2x - 3x)", "Moderate (5x - 7x)"
    val leverageExplanation: String,
    val invalidationCondition: String
)

/**
 * Timeframe status condition for multi-timeframe confirmation (1m, 5m, 15m, 30m, 1h, 4h, 1d, 1w).
 */
data class TimeframeCondition(
    val timeframe: CandleTimeframe,
    val stance: String, // "BULLISH", "BEARISH", "NEUTRAL"
    val summary: String,
    val trendDescription: String,
    val keyLevel: String?
)

/**
 * Detailed explanation when NO TRADE is triggered.
 */
data class NoTradeReason(
    val code: String, // "INSUFFICIENT_DATA", "MARKET_DATA_STALE", "CONFLICTING_INDICATORS", "POOR_RISK_REWARD", "NO_RELIABLE_ENTRY_ZONE", "CHOPPY_EQUILIBRIUM"
    val headline: String,
    val detailedExplanation: String,
    val conflictingFactors: List<String>,
    val recommendedAction: String
)

/**
 * Complete AI Trading Signal generated by multi-factor engine.
 */
data class AiTradingSignal(
    val id: String,
    val symbol: String,
    val assetName: String,
    val primaryTimeframe: CandleTimeframe,
    val decision: SignalDecision,
    val confidence: ConfidenceScoreBreakdown,
    val riskPlan: RiskManagementPlan?,
    val noTradeReason: NoTradeReason?,
    val supportingIndicators: List<String>,
    val smcConfirmations: List<String>,
    val timeframeConditions: List<TimeframeCondition>,
    val mtfAgreementCount: Int,
    val mtfTotalCount: Int,
    val mtfAgreementPercent: Int,
    val timestamp: Long = System.currentTimeMillis(),
    val formattedTimestamp: String = SimpleDateFormat("MMM dd, HH:mm:ss", Locale.US).format(Date(timestamp)),
    val dataSource: String = "Binance Public REST / WebSocket",
    val dataFreshness: String = "LIVE",
    val executionWarning: String = "Manual Execution Only — Nexus AI never places automated trades. Always verify your exchange margin and risk parameters."
) {
    /**
     * Converts to legacy Signal model for backwards-compatibility with Dashboard overview.
     */
    fun toLegacySignal(): Signal {
        val type = when (decision) {
            SignalDecision.LONG -> if (confidence.totalScore >= 80) SignalType.STRONG_BUY else SignalType.BUY
            SignalDecision.SHORT -> if (confidence.totalScore >= 80) SignalType.STRONG_SELL else SignalType.SELL
            SignalDecision.NO_TRADE -> SignalType.NEUTRAL
        }

        val entry = riskPlan?.entryZoneFormatted ?: "No Entry"
        val tp = riskPlan?.let { "${it.takeProfit2Formatted} (+${String.format(Locale.US, "%.1f", it.takeProfit2DistancePercent)}%)" } ?: "N/A"
        val sl = riskPlan?.let { "${it.stopLossFormatted} (-${String.format(Locale.US, "%.1f", it.stopLossDistancePercent)}%)" } ?: "N/A"
        val rr = riskPlan?.riskRewardFormatted ?: "N/A"

        val thesisText = if (decision == SignalDecision.NO_TRADE) {
            noTradeReason?.headline ?: "No trade opportunity detected due to conflicting factors."
        } else {
            "Multi-factor confluence: ${confidence.rating} (${confidence.totalScore}% confidence). ${smcConfirmations.take(2).joinToString("; ")}."
        }

        return Signal(
            id = id,
            assetSymbol = symbol,
            assetName = assetName,
            type = type,
            entryPrice = entry,
            targetPrice = tp,
            stopLoss = sl,
            riskReward = rr,
            confidenceScore = confidence.totalScore,
            timeframe = primaryTimeframe.label,
            timestamp = timestamp,
            status = SignalStatus.ACTIVE,
            thesis = thesisText,
            indicators = supportingIndicators.take(3)
        )
    }
}
